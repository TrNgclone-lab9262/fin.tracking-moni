// Hàm parser chuyển đổi dòng CSV sang Transaction object chuẩn
export function parseCsvToTransactions(): Transaction[] {
  return RAW_CSV_DATA.map((line, idx) => {
    // Tách các cột theo dấu phẩy, xử lý nếu có dấu ngoặc kép
    const parts: string[] = [];
    let cur = "";
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        inQuotes = !inQuotes;
      } else if (char === "," && !inQuotes) {
        parts.push(cur.trim());
        cur = "";
      } else {
        cur += char;
      }
    }
    parts.push(cur.trim());

    const [monthCol, stt, dateStr, groupName, itemName, rawAmount, statusStr] = parts;

    // 1. Chuyển đổi ngày tháng DD/MM/YYYY -> YYYY-MM-DD
    let isoDate = "2026-01-01";
    if (dateStr && dateStr.includes("/")) {
      const [d, m, y] = dateStr.split("/");
      isoDate = `${y}-${m.padStart(2, "0")}-${d.padStart(2, "0")}`;
    }

    // 2. Chuyển đổi số tiền
    // Ví dụ: "2.810.000 đ" -> 2810000
    const cleanNum = rawAmount ? rawAmount.replace(/[^0-9]/g, "") : "0";
    const parsedAmount = parseInt(cleanNum, 10) || 0;

    // 3. Xử lý trạng thái TRUE / FALSE
    const isCompleted = statusStr ? statusStr.toUpperCase() === "TRUE" : false;
    // Theo yêu cầu của người dùng: FALSE (hoặc chưa chi) đặt số tiền = 0 để theo dõi ghi chú
    const amount = isCompleted ? parsedAmount : 0;

    // 4. Nhận diện danh mục (categoryId)
    const upperItem = itemName ? itemName.toUpperCase() : "";
    let categoryId = "cat_expense_food"; // Mặc định ăn uống

    if (
      upperItem.includes("TIỀN TRỌ") ||
      upperItem.includes("RÈM CỬA") ||
      upperItem.includes("THÔNG CỐNG")
    ) {
      categoryId = "cat_expense_rent";
    } else if (
      upperItem.includes("SỬA XE") ||
      upperItem.includes("VÁ XE") ||
      upperItem.includes("XE ĐẠP") ||
      upperItem.includes("XĂNG") ||
      upperItem.includes("RỬA XE") ||
      upperItem.includes("THAY NHỚT") ||
      upperItem.includes("ĐI LẠI")
    ) {
      categoryId = "cat_expense_transport";
    } else if (
      upperItem.includes("VÀNG") ||
      upperItem.includes("PĐ SKYONE") ||
      upperItem.includes("SKYONE") ||
      upperItem.includes("TÍCH LŨY") ||
      groupName === "Tài sản"
    ) {
      categoryId = "cat_expense_other";
    } else if (
      upperItem.includes("NGÂN HÀNG") ||
      upperItem.includes("HỤI") ||
      upperItem.includes("TIỀN NỢ") ||
      upperItem.includes("TRẢ NỢ") ||
      upperItem.includes("MACBOOK") ||
      upperItem.includes("TRẢ GÓP") ||
      upperItem.includes("WIFI")
    ) {
      categoryId = "cat_expense_bills";
    } else if (
      upperItem.includes("KHÁM") ||
      upperItem.includes("THUỐC") ||
      upperItem.includes("SỨC KHỎE") ||
      upperItem.includes("SỨC PHẺ") ||
      upperItem.includes("DA LIỄU") ||
      upperItem.includes("XỊT MŨI")
    ) {
      categoryId = "cat_expense_health";
    } else if (
      upperItem.includes("XEM PHIM") ||
      upperItem.includes("PHIM") ||
      upperItem.includes("DU LỊCH") ||
      upperItem.includes("VT TRIP") ||
      upperItem.includes("KARAOKE")
    ) {
      categoryId = "cat_expense_entertainment";
    } else if (
      upperItem.includes("MUA") ||
      upperItem.includes("ÁO") ||
      upperItem.includes("QUẦN") ||
      upperItem.includes("VÁY") ||
      upperItem.includes("ĐẦM") ||
      upperItem.includes("THE CIU") ||
      upperItem.includes("YAME") ||
      upperItem.includes("COOLMATE") ||
      upperItem.includes("HASAKI") ||
      upperItem.includes("MỸ PHẨM") ||
      upperItem.includes("GIÀY") ||
      upperItem.includes("DÉP") ||
      upperItem.includes("BALO") ||
      upperItem.includes("ĐỒNG HỒ") ||
      upperItem.includes("BÀN PHÍM") ||
      upperItem.includes("TAI NGHE") ||
      upperItem.includes("NỒI") ||
      upperItem.includes("QUẠT") ||
      upperItem.includes("MÁY") ||
      upperItem.includes("DIY") ||
      upperItem.includes("WATSON")
    ) {
      categoryId = "cat_expense_shopping";
    }

    // 5. Phân bổ Người chi (memberId) & Tài khoản (accountId)
    let memberId: "HUSBAND" | "WIFE" | "SHARED" = "SHARED";
    let accountId = "acc_husband_vietinbank"; // Mặc định tài khoản chi chính

    if (
      upperItem.includes("ANH TRUNG") ||
      upperItem.includes("CẮT TÓC") ||
      upperItem.includes("POLO") ||
      upperItem.includes("COOLMATE") ||
      upperItem.includes("4MEN")
    ) {
      memberId = "HUSBAND";
      accountId = "acc_husband_bidv";
    } else if (
      upperItem.includes("EM MÈO") ||
      upperItem.includes("MÈO") ||
      upperItem.includes("THE CIU") ||
      upperItem.includes("HASAKI") ||
      upperItem.includes("MỸ PHẨM") ||
      upperItem.includes("ĐẦM") ||
      upperItem.includes("JUNO") ||
      upperItem.includes("RECHIC") ||
      upperItem.includes("BÚP BÊ")
    ) {
      memberId = "WIFE";
      accountId = "acc_wife_acb";
    } else if (upperItem.includes("HIGHLAND") || upperItem.includes("KATINAT") || upperItem.includes("BÚN") || upperItem.includes("PHỞ") || upperItem.includes("SUKIYA") || upperItem.includes("LẨU")) {
      // Ăn uống sinh hoạt chung
      memberId = "SHARED";
      accountId = "acc_family_cash";
    }

    // Ghi chú hoàn chỉnh
    let noteText = itemName;
    if (!isCompleted && parsedAmount > 0) {
      noteText = `${itemName} [Kế hoạch dự kiến: ${new Intl.NumberFormat("vi-VN").format(parsedAmount)} ₫]`;
    }

    // Tạo ID duy nhất cho giao dịch
    const dateCode = isoDate.replace(/-/g, "").slice(2); // VD: 260101
    const id = `TX${dateCode}_${String(idx + 1).padStart(4, "0")}`;

    return {
      id,
      amount,
      date: isoDate,
      type: "EXPENSE",
      categoryId,
      accountId,
      memberId,
      scope: memberId === "SHARED" ? "FAMILY" : "PERSONAL",
      note: noteText,
      tag: groupName === "Tài sản" ? "INVESTMENT" : groupName === "Cố định" ? "RECURRING" : "NORMAL",
      createdAt: `${isoDate}T08:00:00.000Z`,
      updatedAt: `${isoDate}T08:00:00.000Z`,
    };
  });
}

export const REAL_TRANSACTIONS = parseCsvToTransactions();

